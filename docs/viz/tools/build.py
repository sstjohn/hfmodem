def block(data: dict) -> str:
    return f"{BEGIN}\nconst FIG = {json.dumps(data, sort_keys=True)};\n{END}"


def splice(path: Path, page: str, made: str) -> str:
    head, _, rest = page.partition(BEGIN)
    _, _, tail = rest.partition(END)
    if not rest or not tail:
        raise SystemExit(f"{path} has no generated block to replace")
    return head + made + tail


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="report drift and change nothing")
    a = ap.parse_args(argv)

    stale = []
    for name, make in PAGES.items():
        path = REPO / "docs/viz" / name
        rel = path.relative_to(REPO)
        if not path.exists():
            print(f"{rel} is not in this tree; not checked")
            continue
        page = path.read_text(encoding="utf-8")
        made = splice(path, page, block(make()))
        if made == page:
            print(f"{rel} is current")
        elif a.check:
            stale.append(str(rel))
        else:
            path.write_text(made, encoding="utf-8")
            print(f"{rel} rewritten")

    if stale:
        print(f"out of date, run docs/viz/tools/build.py: {', '.join(stale)}",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
