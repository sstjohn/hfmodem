def sabir() -> dict:
    """Current Sabir geometry and error-free airtime, from emitted samples.

    Rates count full link payload codewords, a DATA header, an ACK and two
    250 ms turnarounds. They exclude session setup and host record overhead.
    They are arithmetic upper bounds, not channel measurements.
    """
    from hfmodem.sabir.arq import ArqConfig, LinkModem
    from hfmodem.sabir.arq.profiles import PROFILES
    from hfmodem.sabir.arq.wire import BLOCK_BYTES, CONNECTIONLESS_BYTES, WIRE_VERSION
    from hfmodem.sabir.floor.mfsk import BASE_HZ, GRID, DATA_UNITS, FLOOR_GEARS, FloorModem
    from hfmodem.sabir.phy.modem import FS, GEARS
    from hfmodem.sabir.phy.preamble import preamble_waveform

    modem = LinkModem(ArqConfig())
    rng = np.random.default_rng(20260919)
    floor_s = FloorModem().duration_s(BLOCK_BYTES)
    fast_s = modem.fast.n_samples(1) / FS
    profiles = []
    for profile in PROFILES.values():
        codec = modem.fsm.profile_codec(profile.name)
        coded = np.stack([codec.encode_cw(rng.bytes(codec.data_bytes))
                          for _ in range(profile.frame_cws)])
        wave, symbols = modem.encode_body(profile, coded)
        seconds = len(wave) / FS
        payload = profile.frame_cws * codec.data_bytes
        entry = {"name": profile.name, "id": profile.id,
                 "payload_bytes": payload, "codewords": profile.frame_cws,
                 "symbols": symbols, "body_s": round(seconds, 6),
                 "floor_cycle_bps": round(8 * payload / (seconds + 2 * floor_s + .5), 1),
                 "fast_cycle_bps": None if profile.floor else
                     round(8 * payload / (seconds + 2 * fast_s + .5), 1)}
        if not profile.floor:
            gear = GEARS[profile.name]
            carriers = [round(float(f), 4) for f in gear.carrier_hz]
            entry.update(carriers=carriers, spacing_hz=FS / gear.n_fft,
                         allocation_hz=gear.n_carriers * FS / gear.n_fft,
                         filter_hz=list(gear.passband_hz),
                         constellation=gear.constellation, code=gear.code,
                         repeat=gear.repeat, n_fft=gear.n_fft, cp=gear.cp,
                         psd=_psd(wave.real, FS, 8192, 3200))
        profiles.append(entry)
    controls = {name: {"session_s": round(fm.duration_s(BLOCK_BYTES), 6),
                      "compact_s": round(fm.duration_s(CONNECTIONLESS_BYTES), 6)}
                for name, gear in FLOOR_GEARS.items() if (fm := FloorModem(gear))}
    measurements = REPO / "docs/protocols/sabir/measurements.json"
    return {"profiles": profiles, "wire_version": WIRE_VERSION,
            "session_bytes": BLOCK_BYTES, "compact_bytes": CONNECTIONLESS_BYTES,
            "floor_tones": [BASE_HZ + u * GRID for u in DATA_UNITS],
            "controls": controls, "fast_control_s": round(fast_s, 6),
            "preamble_s": len(preamble_waveform()) / FS,
            "measurements": json.loads(measurements.read_text())
                if measurements.exists() else None}


def kernels() -> dict:
    """shrike's transmit pulse, computed here the same way the modem computes it.

    There are no shipped bytes behind this figure because there is no shipped
    table: `symbol_pulse` is a root-raised cosine evaluated at import, and what
    the modulator convolves with is what this plots.
    """
    from hfmodem.shrike import tablegen

    taps = tablegen.symbol_pulse()
    fs = tablegen.SPS * 100.0
    grid = 4096
    mag = np.abs(np.fft.rfft(taps, grid))
    freqs = np.fft.rfftfreq(grid, 1 / fs)
    db = 20 * np.log10(mag / mag.max() + 1e-12)
    keep = (freqs <= 200)[::4]
    return {"rolloff": round(float(tablegen.ROLLOFF), 6), "sps": int(tablegen.SPS),
            "taps": [round(float(t), 6) for t in taps],
            "response": {"hz": [round(float(f), 2) for f in freqs[::4][keep]],
                         "db": [round(float(v), 2) for v in db[::4][keep]]}}


