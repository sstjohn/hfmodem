"""Reed-Solomon codes over GF(16) (MIL-STD-188-110B B.5.2): the field of
polynomials over GF(2) modulo x^4 + x + 1, the (15,11) code generated by
g(x) = x^4 + a^13 x^3 + a^6 x^2 + a^3 x + a^10, shortened.

A codeword is written highest degree first: its data symbols, then the four
parity symbols (the remainder of data * x^4 by g). Decoding corrects up to
two symbol errors, or four erasures, or any mix with 2e + f <= 4.
"""
from __future__ import annotations

import numpy as np

EXP = np.zeros(30, dtype=np.int64)
LOG = np.zeros(16, dtype=np.int64)
_v = 1
for _i in range(15):
    EXP[_i] = _v
    LOG[_v] = _i
    _v <<= 1
    if _v & 0x10:
        _v ^= 0x13                        # x^4 + x + 1
EXP[15:] = EXP[:15]


def mul(a: int, b: int) -> int:
    return 0 if a == 0 or b == 0 else int(EXP[(LOG[a] + LOG[b]) % 15])


def div(a: int, b: int) -> int:
    if b == 0:
        raise ZeroDivisionError
    return 0 if a == 0 else int(EXP[(LOG[a] - LOG[b]) % 15])


def pw(i: int) -> int:
    return int(EXP[i % 15])


#: g(x), highest degree first.
G = [1, pw(13), pw(6), pw(3), pw(10)]


def _roots() -> list[int]:
    """The exponents i with g(a^i) = 0 (four consecutive powers)."""
    out = []
    for i in range(15):
        x, acc = pw(i), 0
        for c in G:
            acc = mul(acc, x) ^ c
        if acc == 0:
            out.append(i)
    return out


ROOTS = _roots()


def encode(data) -> list[int]:
    """Data symbols (0-15, highest degree first) -> data + four parity."""
    reg = [0, 0, 0, 0]
    for d in data:
        fb = d ^ reg[0]
        reg = [reg[1] ^ mul(fb, G[1]), reg[2] ^ mul(fb, G[2]), reg[3] ^ mul(fb, G[3]),
               mul(fb, G[4])]
    return list(data) + reg


def syndromes(cw) -> list[int]:
    out = []
    for r in ROOTS:
        x, acc = pw(r), 0
        for c in cw:
            acc = mul(acc, x) ^ c
        out.append(acc)
    return out


def decode(cw, erasures=()) -> tuple[list[int], int] | None:
    """(corrected codeword, symbols corrected), or None if it cannot be.
    ``erasures``: positions (0 = first sent) known to be unreliable."""
    n = len(cw)
    s = syndromes(cw)
    if not any(s) and not erasures:
        return list(cw), 0
    b0 = ROOTS[0]
    # Erasure locator from positions (degree n-1-p).
    locs = [pw(n - 1 - p) for p in erasures]
    if len(locs) > 4:
        return None
    gamma = [1]
    for X in locs:                                   # prod (1 - X z)
        gamma = _pmul(gamma, [1, X])
    # Modified syndromes: T(z) = S(z) Gamma(z) mod z^4 (low degree first).
    S = s                                            # S_j = r(a^(b0+j)), j = 0..3
    T = _pmul(S, gamma)[:4]
    # Berlekamp-Massey on T[len(locs):] for the errors.
    f = len(locs)
    lam, B, L, m, bb = [1], [1], 0, 1, 1
    for k in range(f, 4):
        d = T[k]
        for i in range(1, L + 1):
            if i < len(lam) and k - i >= 0:
                d ^= mul(lam[i], T[k - i])
        if d == 0:
            m += 1
        elif 2 * L <= k - f:
            tmp = lam[:]
            lam = _padd(lam, _pscale(_shift(B, m), div(d, bb)))
            L, B, bb, m = k - f + 1 - L, tmp, d, 1
        else:
            lam = _padd(lam, _pscale(_shift(B, m), div(d, bb)))
            m += 1
    psi = _pmul(lam, gamma)                          # errata locator (low first)
    # Roots of psi: positions.
    pos = []
    for p in range(n):
        Xinv = pw(-(n - 1 - p))
        if _peval(psi, Xinv) == 0:
            pos.append(p)
    if len(pos) != max(i for i, c in enumerate(psi) if c):
        return None                                  # not all its roots are positions
    omega = _pmul(S, psi)[:4]
    dpsi = [psi[i] if i % 2 == 1 else 0 for i in range(1, len(psi))]   # formal derivative
    out = list(cw)
    for p in pos:
        X = pw(n - 1 - p)
        Xinv = pw(-(n - 1 - p))
        num = _peval(omega, Xinv)
        den = _peval(dpsi, Xinv)
        if den == 0:
            return None
        # Forney, for syndromes starting at a^b0.
        e = mul(num, div(1, den))
        e = mul(e, pw(-(b0 - 1) * (n - 1 - p)))
        out[p] ^= e
    if any(syndromes(out)):
        return None
    return out, len(pos)


def _pmul(a, b):
    out = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            out[i + j] ^= mul(x, y)
    return out


def _padd(a, b):
    n = max(len(a), len(b))
    return [(a[i] if i < len(a) else 0) ^ (b[i] if i < len(b) else 0) for i in range(n)]


def _pscale(a, c):
    return [mul(x, c) for x in a]


def _shift(a, m):
    return [0] * m + a


def _peval(p, x):
    acc, xp = 0, 1
    for c in p:
        acc ^= mul(c, xp)
        xp = mul(xp, x)
    return acc
