# physical demod
#: Per-bin level below which there is nothing to equalise. A clean synthesised burst
#: reads exactly zero in every unlit bin, so an unfloored division by that level is a
#: division by numerical dust and the argmax follows the dust.
_BIN_FLOOR = 1e-3


def retune(audio: np.ndarray, hz: float) -> np.ndarray:
    """``audio`` as it reads with a station ``hz`` off our grid moved onto it.

    The index-law bins are 23-94 Hz wide, so a peer 29 Hz off lights the bin
    beside its own at record 0 and splits two at records 1-2: N0LCR-1's resends
    at both, 40 m 2026-09-27, scored 3-7 of 24 reference columns where they read
    24 and a clean CRC retuned. One transform of the whole buffer, its bins
    rolled."""
    x = np.asarray(audio, float)
    if not hz or not len(x):
        return x
    n = _fft.next_fast_len(len(x), real=True)
    k = round(-hz * n / FS)
    spec = np.roll(_fft.rfft(x, n), k)
    if k > 0:
        spec[:k] = 0
    elif k < 0:
        spec[k:] = 0
    return _fft.irfft(spec, n)[:len(x)]


def _band_mag(audio: np.ndarray, level: int, ncol: int) -> np.ndarray:
    """``ncol × span`` matrix of one-hot-band readings, one row per 512-column.

    Equalised per bin. One column lights one bin of ``span``, so the median down a
    bin is what that bin reads while unlit — its share of the channel's frequency
    response plus whatever else is sitting on it — and dividing it out puts every
    bin's lit and unlit readings on one scale before anything takes an argmax.

    Without it the argmax follows the channel rather than the payload. On the
    2026-08-19 KC9GHZ over the four bins around 1.3 kHz read 2-4x the rest of the
    band across the whole 4.2 s frame; all six of the reference columns that missed
    missed *into* those four bins, the frame scored 18 of 24 and would not decode,
    and equalised it scores 20 and decodes to a clean CRC.
    """
    r = RECORDS[level]
    blocks = np.asarray(audio[:ncol * r.dw50], float).reshape(ncol, r.dw50)
    mag = np.abs(np.fft.rfft(blocks, axis=1)[:, r.first_bin:r.first_bin + r.span])
    return mag / np.maximum(np.median(mag, axis=0), _BIN_FLOOR * mag.max() + 1e-12)


#: Onsets the reference-column searches score per column: every 16 samples of
#: the base record's 512, where each of the five real overs of the off-air corpus
#: scores what it scores at every 4, and the same share of a column below it.
ONSETS = 32


def hop(level: int) -> int:
    return RECORDS[level].dw50 // ONSETS


@cache
def _hop_kernels(level: int) -> tuple:
    r = RECORDS[level]
    k = r.first_bin + np.arange(r.span)
    return (np.exp(-2j * np.pi * np.outer(np.arange(hop(level)), k) / r.dw50),
            np.exp(-2j * np.pi * np.outer(np.arange(ONSETS), k) / ONSETS))


def _hop_band(x: np.ndarray, level: int, hz: float = 0.0) -> np.ndarray:
    """``level``'s one-hot band as :func:`_band_mag` reads it unequalised, for the
    column starting at every :func:`hop` of ``x``, read ``hz`` off our grid.

    One pass for every onset of the search: each column is the running sum of
    its hop-long pieces' transforms, so the grid costs the band's bins per
    sample rather than a transform per column per onset."""
    r = RECORDS[level]
    step = hop(level)
    n = len(x) // step
    if n < ONSETS:
        return np.zeros((0, r.span))
    inner, outer = _hop_kernels(level)
    if hz:
        inner = inner * np.exp(-2j * np.pi * hz / FS * np.arange(step))[:, None]
    piece = np.asarray(x[:n * step], float).reshape(n, step) @ inner
    piece *= np.resize(outer, (n, r.span))
    if hz:
        piece *= np.exp(-2j * np.pi * hz * step / FS * np.arange(n))[:, None]
    run = np.concatenate([np.zeros((1, r.span)), np.cumsum(piece, axis=0)])
    return np.abs(run[ONSETS:] - run[:-ONSETS])


class HopBands:
    """:func:`_hop_band` of the audio a stream has heard, kept as it arrives.

    A search handed the stream's newest audio again, as a live one is every scan,
    transforms only the columns that are new; any other audio is transformed
    whole. The grid is the stream's own, so an onset scored in one scan is the
    same onset in the next whatever the buffer's first sample."""

    def __init__(self, keep: int):
        self._keep = keep
        self._x = np.zeros(2 * keep)
        self._n = 0                 # samples held
        self._end = 0               # stream samples heard
        self._rows: dict = {}       # comb -> (hz, stream sample of row 0, rows)

    def feed(self, samples: np.ndarray) -> None:
        n = len(samples)
        if self._n + n > len(self._x):
            held = self._x[max(0, self._n - self._keep):self._n]
            self._x = np.zeros(max(2 * self._keep, len(held) + n))
            self._x[:len(held)] = held
            self._n = len(held)
        self._x[self._n:self._n + n] = samples
        self._n += n
        self._end += n

    def start(self, x: np.ndarray) -> int | None:
        """The stream sample ``x`` starts at, if it is the audio last heard."""
        n = len(x)
        if not 0 < n <= min(self._n, self._keep) or not np.array_equal(
                self._x[self._n - n:self._n], x):
            return None
        return self._end - n

    def band(self, x: np.ndarray, level: int, hz: float = 0.0,
             pad: int = 0) -> tuple[np.ndarray, int]:
        """``(rows, d)``: :func:`_hop_band` of ``pad`` zeros and then ``x``, row 0
        at sample ``d`` of that."""
        r, step = RECORDS[level], hop(level)
        at = self.start(x)
        d = 0 if at is None else -at % step
        if at is None or len(x) < d + r.dw50:
            return _hop_band(np.concatenate([np.zeros(pad), x]), level, hz), 0
        comb = r.dw50, r.first_bin, r.span
        p0, last = at + d, self._end - r.dw50
        have, first, rows = self._rows.get(comb, (None, 0, None))
        held = self._end - self._n
        if have != hz or first > p0:
            first, rows = p0, _hop_band(self._x[p0 - held:self._n], level, hz)
        else:
            nxt = first + step * len(rows)
            if nxt <= last:
                rows = np.concatenate(
                    [rows, _hop_band(self._x[nxt - held:self._n], level, hz)])
            cut = (max(held, self._end - self._keep) - first + step - 1) // step
            if cut > 0:
                first, rows = first + step * cut, rows[cut:]
        self._rows[comb] = hz, first, rows
        body = rows[(p0 - first) // step:(last - first) // step + 1]
        if not pad:
            return body, d
        head = np.concatenate([np.zeros(pad), x[:d + r.dw50 - step]])[d:]
        return np.concatenate([_hop_band(head, level, hz), body]), d


