# A const-law over, named without decoding it: the cyclic-prefix repetition.

#: Prefix length every candidate symbol is scored with: BW2300's ``cp``, and
#: nothing measured says BW2750's high-SL symbol differs (spec/01 §2750).
CP_SAMPLES = 128

#: Useful symbol lengths searched: BW2300's 1024 and the 1258-1394 spread BW2750's
#: high-SL estimates fall in (spec/06 §6.1b), to where the prefix search ends.
CP_USEFUL = range(1000, 1301)
_CP_BAND_HZ = (200.0, 3000.0)
_CP_LEADS = 2                   # candidate useful lengths the fold is spent on
_CP_REFINE = 2                  # samples either side of a candidate folded too
_CP_STEP = 8                    # phases of the symbol the prefix window is read at

#: The :func:`cp_repetition` metric an over has to reach to be called CP-OFDM.
#: Synthesized rec9/12/15 overs read 0.14-0.17 at 0 dB SNR in 2500 Hz and 0.34-0.35
#: at +5 dB, and a 300-2900 Hz CP-OFDM at useful 1250-1290 the same; every no-CP
#: over on tape (records 0-3, BW2750's base) and every 5 s window of the regression
#: corpus reads 0.060 or less.
CP_FLOOR = 0.11


def _cp_fold(z: np.ndarray, ce: np.ndarray, lag: int, period: int) -> float:
    c = np.concatenate([[0], np.cumsum(z[:-lag] * np.conj(z[lag:]))])
    rows = (len(c) - 1 - CP_SAMPLES) // period
    at = (np.arange(rows)[:, None] * period + np.arange(0, period, _CP_STEP)).ravel()
    corr = np.abs(c[at + CP_SAMPLES] - c[at])
    energy = ce[at + CP_SAMPLES] - ce[at] + ce[at + lag + CP_SAMPLES] - ce[at + lag]
    fold = (corr.reshape(rows, -1).sum(0)
            / (energy.reshape(rows, -1).sum(0) / 2 + 1e-30))
    return float(fold.max() - np.median(fold))


def cp_repetition(audio: np.ndarray) -> tuple[int, float]:
    """``(useful, metric)``: the useful symbol length at which ``audio`` best
    repeats the last :data:`CP_SAMPLES` of every symbol at the head of the next,
    and how strongly. The symbol is ``useful + CP_SAMPLES`` long.

    The in-band analytic signal is correlated with itself one useful length later
    over a prefix-long window, normalised by the window's energy and folded at the
    symbol period; a prefix lines up at one phase of every symbol, so the folded
    profile peaks there over its median. A tone or an FSK keying peaks too, when
    the period beats against its cycle, and it goes on peaking with the lag moved
    half a prefix either way, where a prefix decorrelates within a few samples of
    its own lag. The metric is the peak at the useful length less the larger of
    those two.

    The fold is sharp in the period, a sample off loses more than half of it over
    a 5 s over, so it is not scanned. The whole-burst autocorrelation is: a prefix
    adds up in phase at its useful length across every symbol, a spike over the
    lags beside it, and the fold is spent on the few lags that spike most."""
    from scipy.signal import medfilt
    x = np.asarray(audio, float)
    top = CP_USEFUL.stop + CP_SAMPLES // 2
    if len(x) < top + 4 * (top + CP_SAMPLES):
        return CP_USEFUL.start, 0.0
    spec = np.fft.rfft(x)
    f = np.fft.rfftfreq(len(x), 1 / FS)
    spec[(f < _CP_BAND_HZ[0]) | (f > _CP_BAND_HZ[1])] = 0
    full = np.concatenate([spec, np.zeros(len(x) - len(spec))])
    z = np.fft.ifft(full)
    ce = np.concatenate([[0], np.cumsum(np.abs(z) ** 2)])
    lo = CP_USEFUL.start - CP_SAMPLES // 2
    rho = np.abs(np.fft.ifft(np.abs(full) ** 2)[lo:top + 1])
    spike = (rho - medfilt(rho, CP_SAMPLES + 1))[CP_SAMPLES // 2:-CP_SAMPLES // 2]
    leads: list[int] = []
    for k in np.argsort(spike)[::-1]:
        if all(abs(k - j) > 2 * _CP_REFINE for j in leads):
            leads.append(int(k))
            if len(leads) == _CP_LEADS:
                break
    peaks = {u: _cp_fold(z, ce, u, u + CP_SAMPLES)
             for k in leads
             for u in range(max(CP_USEFUL.start, CP_USEFUL.start + k - _CP_REFINE),
                            min(CP_USEFUL.stop, CP_USEFUL.start + k + _CP_REFINE + 1))}
    useful = max(peaks, key=peaks.get)
    aside = max(_cp_fold(z, ce, useful + d, useful + CP_SAMPLES)
                for d in (-CP_SAMPLES // 2, CP_SAMPLES // 2))
    return useful, peaks[useful] - aside
