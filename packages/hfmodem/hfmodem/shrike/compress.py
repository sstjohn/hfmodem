_PARTS = {
    spec.DataType.HUFFMAN: (False, False, False),
    spec.DataType.HUFFMAN_SWAPPED: (False, False, True),
    spec.DataType.PMC_GERMAN: (True, False, False),
    spec.DataType.PMC_GERMAN_SWAPPED: (True, False, True),
    spec.DataType.PMC_ENGLISH: (True, True, False),
    spec.DataType.PMC_ENGLISH_SWAPPED: (True, True, True),
}
"""(pmc, english, swapped) per data-type code. The three bits do not decompose
uniformly: 0b010 means swapped for plain Huffman but English for PMC."""


class Decoder:
    """One link direction's character stream, taken a packet field at a time.

    The coding trees restart with every field (module header), but the
    run-length layer rides the CHARACTER stream, which is continuous across
    fields: a run may put its prefix at the end of one packet and its code and
    count at the start of the next. Measured on the DL6MAA transfer -- the
    eleven-dash rule under "Allgemeines" arrives split exactly there, and
    per-field expansion prints "-" and "-j" where the peer wrote a line. So
    the one thing carried from field to field is an unfinished run's pending
    symbols, at most two of them.

    `feed` is total over every value the status byte's three-bit field can
    hold: ASCII_8BIT skips the coding trees but still expands runs; only the
    reserved value passes through untouched. A pure idle fill, what an ISS with an empty buffer
    transmits, decodes to b"".

    What comes out is still the wire's CHARACTER stream, not the host's bytes:
    `Supervisor` is the layer above this one and the peer's 0x1C blocks are
    still in here.
    """

    def __init__(self):
        self._pending: list[int] = []

    def feed(self, data: bytes, data_type: int) -> bytes:
        part = _PARTS.get(data_type)
        if data_type == spec.DataType.ASCII_8BIT:
            # The SCS reference decoder expands 1D FF 5C to 92 FF bytes in a type-0 P3 field.
            # Preserve a partial run across packets, just as for coded modes.
            symbols = self._pending + [s for s in data if s != spec.IDLE]
            expanded, self._pending = _expand_runs(symbols)
            return bytes(expanded)
        if part is None:
            self._pending.clear()
            return data
        pmc, english, swapped = part
        symbols = self._pending + [s for s in _symbols(data, pmc, english)
                                   if s != spec.IDLE]
        expanded, self._pending = _expand_runs(symbols)
        out = bytes(expanded)
        return out.translate(_SWAP) if swapped else out


def decompress(data: bytes, data_type: int) -> bytes:
    """One field on its own; a stream of them wants a `Decoder`."""
    return Decoder().feed(data, data_type)


def _symbols(data: bytes, pmc: bool, english: bool):
    """Walk the coding trees over `data`, yielding 8-bit characters and IDLE."""
    bit = _bits(data)
    table_offset = 0
    try:
        while True:
            offset = 0
            while True:
                if next(bit):
                    offset += 2
                offset = HUFTAB[(table_offset + offset) >> 1]
                if offset > 767:
                    break
            symbol = offset & 0xFF
            if pmc:
                # The printed plain-Huffman skeleton restarts the walk only on
                # IDLE where the PMC one restarts unconditionally; restarting
                # only on IDLE cannot decode a second character, so the plain
                # listing is read as a printing slip and both restart.
                context = REFTAB[symbol]
                table_offset = (context + ENGLISH_BIAS
                                if context and english else context)
            if symbol == ESCAPE:
                symbol = 0x80
                for i in range(7):
                    symbol |= next(bit) << i
            yield symbol
    except StopIteration:
        return


def _bits(data: bytes):
    for byte in data:
        for _ in range(8):
            yield byte & 1
            byte >>= 1


def _expand_runs(symbols: list[int]) -> tuple[list[int], list[int]]:
    """Expand the three-symbol run-length code: prefix, code, count.

    Counts 1-31 arrive biased by 0x60 -- so a count is a printable character --
    and other counts below 128 are literal. High-bit counts produce no output
    (the SCS reference decoder: type-0 F3 1D 4B 92 72 delivers F3 72). A run left unfinished
    at the end comes back as the second element, for the next field to
    complete."""
    out: list[int] = []
    i = 0
    while i < len(symbols):
        if symbols[i] == RUN_PREFIX:
            if i + 2 >= len(symbols):
                return out, symbols[i:]
            code, sent = symbols[i + 1], symbols[i + 2]
            count = sent - 0x60 if 0x61 <= sent <= 0x7F else sent
            out.extend([code] * (count if sent < 0x80 else 0))
            i += 3
        else:
            out.append(symbols[i])
            i += 1
    return out, []


_SWAP = bytes(b ^ 0x20 if 65 <= b <= 90 or 97 <= b <= 122 else b
              for b in range(256))
"""ASCII case swap as a translation table: the swapped modes code text in the
opposite case (upper-case-heavy traffic compresses better inverted)."""


