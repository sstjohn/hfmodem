"""PACTOR online data compression, receive side: Huffman, PMC and run length.

The published protocol description prints the decoder skeletons and the whole of
both coding tables, and states that PACTOR-2, -3 and -4 share them (SCS PACTOR-4
protocol description §12, pp. 22-41). `HUFTAB` and `REFTAB` below are that
printed data, transcribed.

`HUFTAB` is 33 consecutive 254-entry trees: the plain Huffman tree first, then
sixteen German PMC context trees, then the same sixteen for English. Every tree
is a complete binary tree over the 128-symbol alphabet -- 127 internal nodes,
two entries each. An entry below 768 is the offset of a child node in the same
tree, in units of two bytes; an entry above 767 is a leaf carrying its symbol in
the low byte. `REFTAB[c]` is the offset of the context tree to use after
emitting `c`, or zero for the 112 characters that fall back to plain Huffman.
Bits are consumed least-significant first within each byte.

DECODE SIDE ONLY for the compressors: shrike transmits ASCII_8BIT
(`spec.DataType`), so no coding tree is walked forwards here -- but a receiver
reads what the peer's status byte declares, and a real station declares all of
it: the DL6MAA recording in the regression corpus carries PMC German, PMC
English and case-swapped fields in one transfer. The supervisor layer above the
compressors runs BOTH ways (`transparent`, `Supervisor`); it is the only thing
that makes 0x1C, 0x1D and 0x1E reach a peer as data.

Three facts the printed skeletons do not state, each measured on that recording
-- it carries the SCS PTC-II manual, so the plaintext is known:

  * EVERY FIELD IS CODED FRESH. The coder's context does not carry from one
    packet to the next: decoded independently, each field opens in clean
    plaintext and the concatenation reads continuously; decoded as one stream,
    every field boundary opens tens of characters of soup. Text still SPANS
    fields -- "Datentransparenz" arrives split "...Datentransparen" + "z" -- it
    is the coder state that restarts, not the sentence. The run-length layer
    rides the sentence, not the coder, and is the one carry (`Decoder`).
  * SYMBOL 0x7F IS AN ESCAPE, not a character. Seven raw bits follow it in the
    same bit stream, least significant first, and the character is 0x80 plus
    their value. Read as a character instead, every umlaut in the German text
    opens a desynchronised stretch that runs until the tree walk happens to
    realign.
  * THE HIGH HALF IS CODEPAGE 437 -- the PTC's own terminal charset. "verf" +
    0x81 + "gbar", 0x94 in "m*glich", 0x84 in "sch*dliche", byte for byte.
    `decompress` returns the 8-bit stream; render it with `.decode("cp437")`.

PACTOR-1 declares its data mode in two status bits rather than three, and its
original Huffman table is not printed in the reference held here; whether it
matches the plain tree below is open. Winlink PACTOR-1 traffic measures type 0,
8-bit ASCII -- but "8-bit" does not mean transparent. 0x1E is IDLE and 0x1C
opens a supervisor block. The SCS reference decoder also expands raw 0x1D runs
in uncompressed P3 fields (2026-09-20 saved mail transfers); `transparent` quotes all three.
"""
from __future__ import annotations

from . import spec

RUN_PREFIX = 0x1D
"""Head of the three-symbol run-length code: prefix, code symbol, count."""

ESCAPE = 0x7F
"""The 8-bit escape: seven raw bits follow, the character is 0x80 + their value."""

ENGLISH_BIAS = 8128
"""Sixteen German context trees separate a context tree from its English twin."""

SB = 0x1C
"""ASCII FS, the supervisor byte: "das die normale Textausgabe auf die
Systemebene umlenkt". The byte after it is the supervisor function code."""

SIC_CONTROL = 0x60
"""SIC `a`..<DEL> minus the control character it carries, 0x01 to 0x1F --
"ermoeglicht volle Datentransparenz", and the only transparency PACTOR-1 has."""

SI_END = 0x20
"""<SPACE> closes a supervisor block that carries parameters rather than a
control character."""


def transparent(data: bytes) -> bytes:
    """`data` written so a PACTOR character stream carries it byte for byte.

    Three values are the stream's own: 0x1E is IDLE, 0x1C opens a supervisor
    block, and 0x1D opens a run even in uncompressed P3 packets. They use the two-byte
    supervisor sequence the 1990 description reserves for control characters.

    MEASURED against SCS's own monitor, 2026-09-01, at 200 Bd: the field
    `41 1c 7e 20 42 1c 7c 20 43 ...` reads back `A`, 0x1E, <SPACE>, `B`, 0x1C,
    <SPACE>, `C` -- so the SIC carries the character on its own and the space
    after it is ordinary text, not a terminator. A block whose SIC is outside
    `a`..<DEL> IS terminated by a space and yields nothing: `1c 1d 1e 1f 20`
    inside a run of 0x00-0xFF took all five bytes off the stream. Both rules
    hold across a packet boundary -- `1c` ending one field and `7e` opening the
    next still delivered one 0x1E."""
    out = bytearray()
    for byte in data:
        if byte in (spec.IDLE, SB, RUN_PREFIX):
            out += bytes((SB, SIC_CONTROL + byte))
        else:
            out.append(byte)
    return bytes(out)


def bit_stream(data_type: int) -> bool:
    """Whether a field of this mode is a coded BIT stream rather than bytes.

    IDLE is a SYMBOL, "in beiden Faellen" -- so under a coded mode it is a code
    word and the byte 0x1E means nothing. DL6MAA's 200 Bd announcement is the
    proof on tape: eight bytes of Huffman then twelve of `spec.TEMPLATE`
    resumed at its ninth byte, `1e 1e` among them. Take those two out as
    padding and the bit stream desynchronises -- `1dl6maa\r` becomes
    `1dl6maa\r\x0frg d g d g d`."""
    return data_type in _PARTS


_TEXT, _SIC, _PARAMETERS = range(3)


class Supervisor:
    """One link direction's character stream turned back into host bytes.

    The inverse of `transparent`, and the layer above the compressors: "die
    gesamte SI laeuft wie gewoehnlicher Text ueber das PT-System", so a block
    is read after the coding trees rather than before them. Stateful, because a
    block can put its SB at the end of one packet and its function code at the
    start of the next -- MEASURED, `41*19 1c` then `7e 42*19` delivered one
    0x1E and nineteen `B`, and a parameter block's <SPACE> terminator closed it
    across the boundary just as readily.

    IT GOES ON THE LINK WITH `transparent` OR NOT AT ALL. The two are one
    change: a receiver that reads blocks off a transmitter that never writes
    them loses every 0x1C the host queued, and `test_mail`'s loopback catches
    that half. It cannot catch the absence of both -- `ptc.SimPeer` carries a
    payload as bytes and renders no field, so nothing there drops an IDLE. The
    witness for the pair is a keyed link, `test_p1transparent`.
    """

    def __init__(self):
        self._state = _TEXT

    def feed(self, chars: bytes) -> bytes:
        out = bytearray()
        for c in chars:
            if c == spec.IDLE:
                continue
            if self._state == _SIC:
                if SIC_CONTROL < c <= SIC_CONTROL + 0x1F:
                    out.append(c - SIC_CONTROL)
                    self._state = _TEXT
                else:
                    self._state = _PARAMETERS
            elif self._state == _PARAMETERS:
                if c == SI_END:
                    self._state = _TEXT
            elif c == SB:
                self._state = _SIC
            else:
                out.append(c)
        return bytes(out)


